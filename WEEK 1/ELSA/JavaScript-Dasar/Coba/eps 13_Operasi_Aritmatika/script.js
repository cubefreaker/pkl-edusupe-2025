// operator aritmatika

// ekspresi (expression) dan statament

// */+- 
// % <- modulo
// ++ <- increment
// -- <- decrement
// ** <- pangkat / power

let x = 10
console.log(x + 1);
console.log(x - 1);
console.log(x / 1);
console.log(x * 1);

// aritmatikan khusu di javascript
console.log(x % 3); // sisa pembagian
console.log(x ** 2);

// pemograman biasa
x = x + 1;
console.log(x);
x = x + 1;
console.log(x);
x++;
x++;
console.log(x);

x = x - 1;
console.log(x);
x--;
console.log(x);

